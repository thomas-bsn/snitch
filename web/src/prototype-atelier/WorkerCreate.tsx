export function WorkerCreate({
  lang = "en",
  onDone,
  skip,
}: {
  lang?: "en" | "fr";
  onDone: () => void;
  skip?: React.ReactNode;
}) {
  const t = D[lang];
  const profile = useProfile();
  const workers = useWorkers();
  const first = !profile;
  const api = location.origin;
  const insecure = !api.toLowerCase().startsWith("https://");
  const [f, setF] = useState({
    name: `worker-${workers.length + 1}`,
    url: "",
    model: "",
    language: "fr",
    alias: "",
    hf: "",
  });
  const [confirming, setConfirming] = useState(false);
  const [made, setMade] = useState(false);
  const [tab, setTab] = useState<"compose" | "env">("env");
  const [copied, setCopied] = useState(false);
  const set =
    (k: keyof typeof f) =>
    (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) =>
      setF({ ...f, [k]: e.target.value });

  const create = () => {
    store.addWorker(
      f.name.trim() || "worker",
      f.url.trim(),
      f.alias.trim(),
      first ? { model: f.model.trim(), language: f.language } : undefined,
    );
    setConfirming(false);
    setMade(true);
  };
  const canCreate = f.url.trim() !== "" && (!first || f.model.trim() !== "");

  const env = [
    "# .env generated by Snitch for this worker. Never commit or share it.",
    ...(insecure
      ? [
          "# WARNING: the Snitch address is not HTTPS and the worker refuses HTTP.",
        ]
      : []),
    "",
    "# --- Connection to Snitch (already filled in) ---",
    `SNITCH_API_URL=${api}`,
    `SNITCH_WORKER_TOKEN=${TOKEN}`,
    `SNITCH_WORKER_IMAGE=${IMAGE}`,
    "",
    "# --- Transcription ---",
    `TRANSCRIPTION_API_URL=${f.url.trim() || A}`,
    f.alias.trim()
      ? `TRANSCRIPTION_MODEL=${f.alias.trim()}`
      : "# TRANSCRIPTION_MODEL=   (optional: name of the model on this server)",
    "# TRANSCRIPTION_API_KEY=",
    "",
    "# --- Voice models ---",
    `HF_TOKEN=${f.hf.trim() || A}`,
    "SNITCH_VOICE_DOWNLOAD_ON_START=1",
    "SNITCH_VOICE_CONFIRM_TERMS=1",
  ].join("\n");
  const todo = [!f.hf.trim() && "HF_TOKEN"].filter(Boolean) as string[];

  if (!made)
    return (
      <div className="stepbox" style={{ width: "100%" }}>
        <label>
          {t.name}
          <input value={f.name} onChange={set("name")} />
        </label>
        <label>
          {t.snitch}
          <input readOnly value={api} />
          <span className="help">{t.snitchHelp}</span>
          {insecure && <span className="warnline">{t.insecure}</span>}
        </label>
        <label>
          {t.url}
          <input
            value={f.url}
            onChange={set("url")}
            placeholder="http://host.docker.internal:8000"
          />
          <span className="help">{t.urlHelp}</span>
        </label>
        {first ? (
          <>
            <label>
              {t.model}
              <input
                value={f.model}
                onChange={set("model")}
                placeholder="whisper-large-v3"
              />
              <span className="help">{t.modelHelp}</span>
            </label>
            <label>
              {t.lang}
              <select value={f.language} onChange={set("language")}>
                <option value="fr">Français (fr)</option>
                <option value="en">English (en)</option>
                <option value="es">Español (es)</option>
                <option value="de">Deutsch (de)</option>
              </select>
              <span className="help">{t.langHelp}</span>
            </label>
          </>
        ) : (
          <>
            <label>
              {t.libModel}
              <input
                readOnly
                value={`${profile!.model} · ${profile!.language}`}
              />
              <span className="help">{t.libModelHelp}</span>
            </label>
            <label>
              {t.alias}
              <input
                value={f.alias}
                onChange={set("alias")}
                placeholder={profile!.model}
              />
              <span className="help">{t.aliasHelp}</span>
            </label>
          </>
        )}
        <label>
          {t.hf}
          <input
            type="password"
            autoComplete="off"
            value={f.hf}
            onChange={set("hf")}
            placeholder="hf_…"
          />
          <span className="help">{t.hfHelp}</span>
        </label>
        <div className="row">
          {skip}
          <button
            className="btn pri"
            disabled={!canCreate}
            onClick={() => (first ? setConfirming(true) : create())}
          >
            {t.create}
          </button>
        </div>
        {confirming && (
          <>
            <div
              className="scrim dim"
              style={{ zIndex: 62 }}
              onClick={() => setConfirming(false)}
            />
            <div
              className="modal"
              style={{ zIndex: 63, width: "min(460px,92vw)" }}
              role="alertdialog"
              aria-modal="true"
              aria-labelledby="fc-t"
            >
              <h2 id="fc-t" style={{ margin: 0 }}>
                {t.confirmT}
              </h2>
              <p style={{ margin: 0 }}>
                <b>{f.model.trim()}</b> · {f.language}
              </p>
              <p className="mute" style={{ margin: 0 }}>
                {t.confirmB}
              </p>
              <div className="row" style={{ justifyContent: "flex-end" }}>
                <button className="btn" onClick={() => setConfirming(false)}>
                  {t.cancel}
                </button>
                <button className="btn pri" onClick={create}>
                  {t.confirm}
                </button>
              </div>
            </div>
          </>
        )}
      </div>
    );

  const text = tab === "env" ? env : COMPOSE;
  return (
    <div className="stepbox" style={{ width: "100%" }}>
      <div className="banner warn">{t.shown}</div>
      {todo.length > 0 && (
        <div className="banner info">
          {t.todo}: {todo.join(", ")}
        </div>
      )}
      <div className="tabs" role="tablist">
        {(["env", "compose"] as const).map((k) => (
          <button
            key={k}
            role="tab"
            aria-selected={tab === k}
            className={tab === k ? "on" : ""}
            onClick={() => setTab(k)}
          >
            {k === "env" ? ".env" : "compose.yaml"}
          </button>
        ))}
      </div>
      {tab === "env" && <span className="mute">{t.secret}</span>}
      <pre style={{ maxHeight: 280 }}>{text}</pre>
      <span className="mute">{t.how}</span>
      <div className="row">
        <button
          className="btn"
          onClick={() => {
            setCopied(true);
            setTimeout(() => setCopied(false), 1500);
          }}
        >
          {copied ? t.copied : t.copy}
        </button>
        <button className="btn">
          {t.download} {tab === "env" ? "snitch-worker.env" : "compose.yaml"}
        </button>
        <button className="btn pri" onClick={onDone}>
          {t.done}
        </button>
      </div>
    </div>
  );
}
